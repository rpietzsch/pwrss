// Build vendor/lucide-sprite.svg from the Lucide icon set (https://lucide.dev, ISC license).
// Usage: node scripts/lucide-sprite.cjs <path to lucide-static package dir>
// Each entry maps our symbol id (used as #i-<id>) to a Lucide icon; `fill` renders the shape filled.
const fs = require('fs');
const path = require('path');

const ICONS = {
  refresh: 'refresh-cw',
  gear: 'settings',
  sidebar: 'panel-left',
  dot: 'circle',
  'dot-fill': ['circle', { fill: true }],
  'check-all': 'check-check',
  back: 'chevron-left',
  up: 'chevron-up',
  down: 'chevron-down',
  chevron: 'chevron-right',
  star: 'star',
  'star-fill': ['star', { fill: true }],
  reader: 'book-open',
  share: 'share',
  external: 'external-link',
  close: 'x',
  inbox: 'inbox',
  folder: 'folder',
  today: 'calendar-days',
  sun: 'sun',
  moon: 'moon',
  'theme-auto': 'sun-moon',
  edit: 'pencil',
  trash: 'trash-2',
  list: 'rss',
  plus: 'plus',
};

const src = path.resolve(process.argv[2] || '');
const out = path.join(__dirname, '..', 'vendor');
if (!fs.existsSync(path.join(src, 'icons'))) { console.error('Usage: node scripts/lucide-sprite.cjs <lucide-static package dir>'); process.exit(1); }

const version = JSON.parse(fs.readFileSync(path.join(src, 'package.json'), 'utf8')).version;
let symbols = '';
for (const [id, spec] of Object.entries(ICONS)) {
  const [name, opts = {}] = Array.isArray(spec) ? spec : [spec];
  const svg = fs.readFileSync(path.join(src, 'icons', `${name}.svg`), 'utf8');
  const inner = svg.replace(/<!--[\s\S]*?-->/g, '').replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '').replace(/\s+/g, ' ').replace(/> </g, '><').trim();
  symbols += `  <symbol id="i-${id}" viewBox="0 0 24 24" fill="${opts.fill ? 'currentColor' : 'none'}" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${inner}</symbol>\n`;
}
fs.writeFileSync(path.join(out, 'lucide-sprite.svg'),
  `<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide v${version} (ISC license, see Lucide.LICENSE). Generated by scripts/lucide-sprite.cjs -->\n${symbols}</svg>\n`);
fs.copyFileSync(path.join(src, 'LICENSE'), path.join(out, 'Lucide.LICENSE'));
console.log(`vendor/lucide-sprite.svg: ${Object.keys(ICONS).length} icons from lucide-static ${version}`);
